// @ts-nocheck — Deno-only one-shot generator (npm: specifiers); keep it out of vue-tsc.
/**
 * Generates utils/navGlobeLand.ts — the land mask behind the News globe nav icon.
 *
 *   deno run -A scripts/nav-globe-land.ts
 *
 * Samples Natural Earth 1:110m land (world-atlas@2) on a STEP° lon/lat grid:
 * cell centres lon = -180+STEP/2 … 180-STEP/2 (west → east),
 *              lat =   90-STEP/2 … -90+STEP/2 (north → south).
 * A cell is 1 when its centre is on land. Bits are packed row-major
 * (rows north → south, columns west → east), MSB first, then base64-encoded.
 * Antarctica (cells south of -62°) is left out: at icon size it only adds a
 * white band along the bottom of the disc.
 */
import land110 from 'npm:world-atlas@2/land-110m.json' with { type: 'json' }
import { feature } from 'npm:topojson-client@3'
import { geoContains } from 'npm:d3-geo@3'

const STEP = 4
const COLS = 360 / STEP // 90
const ROWS = 180 / STEP // 45
const SOUTH_CUTOFF = -62

const land = feature(land110, land110.objects.land)

const bytes = new Uint8Array(Math.ceil((COLS * ROWS) / 8))
let count = 0
for (let row = 0; row < ROWS; row++) {
  const lat = 90 - STEP / 2 - row * STEP
  if (lat < SOUTH_CUTOFF) continue
  for (let col = 0; col < COLS; col++) {
    const lon = -180 + STEP / 2 + col * STEP
    if (!geoContains(land, [lon, lat])) continue
    const i = row * COLS + col
    bytes[i >> 3] |= 0x80 >> (i & 7)
    count++
  }
}

let bin = ''
for (const b of bytes) bin += String.fromCharCode(b)
const b64 = btoa(bin)

const out = `/**
 * GENERATED by scripts/nav-globe-land.ts — do not edit by hand.
 *
 * Source: Natural Earth 1:110m land via npm world-atlas@2 (land-110m.json),
 *         sampled with d3-geo geoContains at each cell centre.
 * Grid:   ${STEP}° cells, ${COLS} columns (west → east from -180°) × ${ROWS} rows
 *         (north → south from +90°), row-major, MSB first, base64.
 *         Cells south of ${SOUTH_CUTOFF}° (Antarctica) are left empty.
 * Land cells: ${count}
 * Generated: ${new Date().toISOString().slice(0, 10)}
 */
export const LAND_STEP_DEG = ${STEP}
export const LAND_COLS = ${COLS}
export const LAND_ROWS = ${ROWS}
export const LAND_BITS = '${b64}'
`

const target = new URL('../utils/navGlobeLand.ts', import.meta.url)
await Deno.writeTextFile(target, out)
console.log(`land cells: ${count} of ${COLS * ROWS} → ${target.pathname}`)
